using System.Collections.Generic;

// Граница между жизненным циклом музыки (MusicMixer — чистая логика) и Unity-аудио
// (MusicPlayer — источники, клипы, dspTime).
//
// Существует ради проверяемости: требования «все слои стартуют в один DSP-момент», «повторный
// контекст не сбрасывает позицию», «после боя не вызывается Stop» — это утверждения ровно об
// этих вызовах. С подставной реализацией они проверяются EditMode-тестами без единого
// AudioSource и без реальных wav в проекте.
public interface IMusicOutput
{
    // Текущее аудио-время. Точка планирования старта считается от него.
    double DspTime { get; }

    // Готовит по источнику на каждый слой, не запуская их. false — набор загрузить не удалось.
    // Прежние источники останавливаются: это единственное место, где смена контекста рвёт звук.
    bool PrepareLayers(IReadOnlyList<string> trackNames);

    // Планирует старт одного слоя на заданный DSP-момент. Микшер вызывает это для всех слоёв
    // с ОДНИМ И ТЕМ ЖЕ значением — отсюда синхронность и сохранение фазы.
    void ScheduleLayer(int index, double dspStartTime);

    void SetLayerVolume(int index, float volume);

    // Полная остановка. Вызывается только при намеренном уходе в тишину и смене контекста —
    // никогда при выходе из боя.
    void StopAllLayers();

    // Отдельный канал под музыку особой комнаты или события. Основная тема на это время не
    // останавливается, а лишь заглушается, чтобы её таймлайн продолжал идти.
    void PlayOverrideTrack(string trackName);
    void StopOverrideTrack();
    void SetOverrideVolume(float volume);
}
